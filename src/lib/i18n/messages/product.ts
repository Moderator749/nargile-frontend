/**
 * A rate (0.05) as a percentage: "%5" in Turkish, as `formatRate` writes it
 * (lib/storeParameters), "5%" in English and Arabic, Latin digits throughout.
 */
export function formatPercent(rate: number | string, locale: Locale): string {
  const value = (Number(rate) * 100).toLocaleString(INTL_LOCALE[locale], { maximumFractionDigits: 2 });
  return locale === "tr" ? `%${value}` : `${value}%`;
}

