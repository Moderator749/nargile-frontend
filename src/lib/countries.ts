const BY_CODE = new Map(COUNTRIES.map((country) => [country.code, country]));

/**
 * The name of a stored country code — English, or Arabic on an Arabic page;
 * the code itself if it is unknown.
 */
export function countryName(code: string | null | undefined, locale: Locale = "en"): string | null {
  if (!code) return null;
  const country = BY_CODE.get(code);
  if (!country) return code;
  return locale === "ar" ? country.ar : country.name;
}

const ARABIC_OPTIONS = COUNTRIES.map(({ code, ar }) => ({ code, name: ar })).sort((a, b) =>
  a.name.localeCompare(b.name, "ar"),
);

/** The list for a country picker, in the page's language and sorted in it. */
export function countryOptions(locale: Locale): readonly { code: string; name: string }[] {
  return locale === "ar" ? ARABIC_OPTIONS : COUNTRIES;
}
